#pragma once
#include <array>
#include <cstdint>
namespace snap::vr {
inline std::array<uint8_t,5> glyph(char c) {
    if(c>='a'&&c<='z')c=char(c-'a'+'A');
    static constexpr uint8_t letters[26][5]={
        {126,9,9,9,126},{127,73,73,73,54},{62,65,65,65,34},{127,65,65,34,28},
        {127,73,73,73,65},{127,9,9,9,1},{62,65,73,73,122},{127,8,8,8,127},
        {65,65,127,65,65},{32,64,65,63,1},{127,8,20,34,65},{127,64,64,64,64},
        {127,2,12,2,127},{127,2,4,8,127},{62,65,65,65,62},{127,9,9,9,6},
        {62,65,81,33,94},{127,9,25,41,70},{38,73,73,73,50},{1,1,127,1,1},
        {63,64,64,64,63},{31,32,64,32,31},{127,32,24,32,127},{99,20,8,20,99},
        {3,4,120,4,3},{97,81,73,69,67}};
    static constexpr uint8_t digits[10][5]={
        {62,81,73,69,62},{0,66,127,64,0},{98,81,73,73,70},{34,65,73,73,54},
        {24,20,18,127,16},{39,69,69,69,57},{62,73,73,73,50},{1,113,9,5,3},
        {54,73,73,73,54},{38,73,73,73,62}};
    std::array<uint8_t,5> result{};
    if(c>='A'&&c<='Z')for(int i=0;i<5;i++)result[i]=letters[c-'A'][i];
    if(c>='0'&&c<='9')for(int i=0;i<5;i++)result[i]=digits[c-'0'][i];
    if(c=='.')result={0,96,96,0,0};
    if(c=='-')result={8,8,8,8,8};
    if(c=='/')result={64,32,16,8,4};
    if(c=='!')result={0,0,95,0,0};
    if(c=='?')result={2,1,81,9,6};
    if(c=='\'')result={0,5,3,0,0};
    if(c==',')result={0,80,48,0,0};
    if(c==':')result={0,54,54,0,0};
    return result;
}
}
